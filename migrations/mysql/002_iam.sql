CREATE TABLE IF NOT EXISTS `system_users` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `creator` varchar(64) NOT NULL DEFAULT '',
  `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updater` varchar(64) NOT NULL DEFAULT '',
  `update_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `deleted` tinyint unsigned NOT NULL DEFAULT '0',
  `tenant_id` bigint NOT NULL,
  `username` varchar(30) NOT NULL,
  `nickname` varchar(30) NOT NULL,
  `password` varchar(100) NOT NULL,
  `dept_id` bigint NOT NULL DEFAULT '0',
  `post_ids` json DEFAULT NULL,
  `email` varchar(100) NOT NULL DEFAULT '',
  `mobile` varchar(30) NOT NULL DEFAULT '',
  `sex` int NOT NULL DEFAULT '0',
  `status` int NOT NULL DEFAULT '0',
  `avatar` varchar(1024) NOT NULL DEFAULT '',
  `remark` varchar(500) NOT NULL DEFAULT '',
  `login_ip` varchar(50) NOT NULL DEFAULT '',
  `login_date` datetime(3) DEFAULT NULL,
  `active_username` varchar(30) DEFAULT NULL,
  `active_mobile` varchar(30) DEFAULT NULL,
  `active_email` varchar(100) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_iam_user_username` (`tenant_id`,`active_username`),
  UNIQUE KEY `uk_iam_user_mobile` (`tenant_id`,`active_mobile`),
  UNIQUE KEY `uk_iam_user_email` (`tenant_id`,`active_email`),
  KEY `idx_system_users_create_time` (`create_time`),
  KEY `idx_system_users_tenant_id` (`tenant_id`),
  KEY `idx_system_users_dept_id` (`dept_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

