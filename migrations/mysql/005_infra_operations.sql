-- Global schedules and execution history. API logs are scoped by tenant_id.
CREATE TABLE IF NOT EXISTS infra_job (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(64) NOT NULL,
  handler_name VARCHAR(64) NOT NULL,
  active_handler VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN deleted = 0 THEN handler_name ELSE NULL END) VIRTUAL,
  handler_param VARCHAR(255) NOT NULL,
  cron_expression VARCHAR(128) NOT NULL,
  status INT NOT NULL,
  retry_count INT NOT NULL,
  retry_interval INT NOT NULL,
  monitor_timeout INT NOT NULL,
  next_run DATETIME(3) NULL,
  manual_pending BOOLEAN NOT NULL DEFAULT FALSE,
  revision BIGINT NOT NULL DEFAULT 0,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
  UNIQUE KEY uk_infra_job_active_handler (active_handler),
  KEY idx_infra_job_due (status, next_run),
  KEY idx_infra_job_manual (manual_pending)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS infra_job_log (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  job_id BIGINT NOT NULL,
  handler_name VARCHAR(64) NOT NULL,
  handler_param VARCHAR(255) NOT NULL,
  cron_expression VARCHAR(128) NOT NULL,
  execute_index INT NOT NULL,
  status INT NOT NULL,
  begin_time DATETIME(3) NOT NULL,
  end_time DATETIME(3) NULL,
  duration BIGINT NOT NULL,
  result TEXT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
  KEY idx_infra_job_log_job_id (job_id),
  KEY idx_infra_job_log_begin_time (begin_time),
  KEY idx_infra_job_log_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS infra_api_access_log (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  trace_id VARCHAR(32) NOT NULL,
  user_id BIGINT NOT NULL,
  user_type INT NOT NULL,
  application_name VARCHAR(64) NOT NULL,
  request_method VARCHAR(16) NOT NULL,
  request_url VARCHAR(512) NOT NULL,
  request_params TEXT NOT NULL,
  user_ip VARCHAR(64) NOT NULL,
  user_agent VARCHAR(512) NOT NULL,
  result_code INT NOT NULL,
  response_body TEXT NOT NULL,
  result_msg VARCHAR(512) NOT NULL,
  operate_module VARCHAR(64) NOT NULL,
  operate_name VARCHAR(64) NOT NULL,
  operate_type INT NOT NULL,
  begin_time DATETIME(3) NOT NULL,
  end_time DATETIME(3) NOT NULL,
  duration BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
  KEY idx_infra_api_access_log_tenant_id (tenant_id, id),
  KEY idx_infra_api_access_log_tenant_begin (tenant_id, begin_time),
  KEY idx_infra_api_access_log_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS infra_api_error_log (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  trace_id VARCHAR(32) NOT NULL,
  user_id BIGINT NOT NULL,
  user_type INT NOT NULL,
  application_name VARCHAR(64) NOT NULL,
  request_method VARCHAR(16) NOT NULL,
  request_url VARCHAR(512) NOT NULL,
  request_params TEXT NOT NULL,
  user_ip VARCHAR(64) NOT NULL,
  user_agent VARCHAR(512) NOT NULL,
  result_code INT NOT NULL,
  exception_time DATETIME(3) NOT NULL,
  exception_name VARCHAR(128) NOT NULL,
  exception_message VARCHAR(512) NOT NULL,
  exception_root_cause_message VARCHAR(512) NOT NULL,
  exception_stack_trace TEXT NOT NULL,
  exception_class_name VARCHAR(255) NOT NULL,
  exception_file_name VARCHAR(255) NOT NULL,
  exception_method_name VARCHAR(255) NOT NULL,
  exception_line_number INT NOT NULL,
  process_status INT NOT NULL,
  process_time DATETIME(3) NULL,
  process_user_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
  KEY idx_infra_api_error_log_tenant_id (tenant_id, id),
  KEY idx_infra_api_error_log_tenant_exception (tenant_id, exception_time),
  KEY idx_infra_api_error_log_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
